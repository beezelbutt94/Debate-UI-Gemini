// ─── PKCE round-trip ──────────────────────────────────────────────────────────

describe('PKCE round-trip (verifier → challenge)', () => {
  it('verifier generated by generateCodeVerifier() produces a 43-char challenge', () => {
    const verifier = generateCodeVerifier();
    expect(codeChallengeFromVerifier(verifier).length).toBe(43);
  });

  it('challenge is a valid base64url string (RFC 7636 requirement)', () => {
    const challenge = codeChallengeFromVerifier(generateCodeVerifier());
    expect(challenge).toMatch(/^[A-Za-z0-9_-]+$/);
  });

  it('two independent verifiers produce two different challenges', () => {
    const v1 = generateCodeVerifier();
    const v2 = generateCodeVerifier();
    expect(codeChallengeFromVerifier(v1)).not.toBe(codeChallengeFromVerifier(v2));
  });

  it('challenge does not change between invocations for the same verifier', () => {
    const v = generateCodeVerifier();
    const c1 = codeChallengeFromVerifier(v);
    const c2 = codeChallengeFromVerifier(v);
    expect(c1).toBe(c2);
  });
});

